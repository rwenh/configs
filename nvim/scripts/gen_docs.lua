-- scripts/gen_docs.lua — generate docs from the live config so they cannot drift.
--   write: nvim --headless "+luafile scripts/gen_docs.lua"
--   check: GEN_DOCS=check nvim --headless "+luafile scripts/gen_docs.lua"   (exit 1 if committed docs are stale)
-- Outputs: docs/KEYMAPS.generated.md, docs/PLUGINS.generated.md
local cfgdir = vim.fn.stdpath("config")
local lib = dofile(cfgdir .. "/tests/lib/keymaps.lua")
local check = vim.env.GEN_DOCS == "check"

local function scope_label(scopes)
  if scopes.global then
    return "global"
  end
  local t = {}
  for s in pairs(scopes) do
    t[#t + 1] = s
  end
  table.sort(t)
  -- attach timing varies per filetype headless; a map present in many fts is "any file (buffer-local)"
  if #t > 3 then
    return "any file (buffer-local)"
  end
  return table.concat(t, ", ")
end

local function esc(s)
  return (s:gsub("|", "\\|"):gsub("\n", " "))
end

local function render_keymaps(db)
  local rows = {}
  for _, e in pairs(db) do
    local ok = e.desc ~= ""
      and e.lhs ~= "<Space>"
      and e.desc ~= "which-key-trigger"
      and not e.desc:find("^LSP:") -- attach-only (needs a live server); non-deterministic headless
      and not e.desc:find("^Java ") -- jdtls attach-only
      and not e.lhs:find("^<Plug>")
      and not e.lhs:find("^<SNR>")
    if ok and (e.lhs:find("^<Space>") or e.lhs:find("^<F%d") or e.lhs:find("^g%a") or e.lhs:find("^[%[%]]%a$")) then
      table.insert(rows, e)
    end
  end
  table.sort(rows, function(a, b)
    if a.lhs ~= b.lhs then
      return a.lhs < b.lhs
    end
    return a.mode < b.mode
  end)
  local out = {
    '<!-- GENERATED by scripts/gen_docs.lua — do not edit. Regenerate: nvim --headless "+luafile scripts/gen_docs.lua" -->',
    "# Keymaps (generated)",
    "",
    "Leader = `Space`. Collected headlessly: global maps, lazy `keys` specs, and buffer-local maps after opening one",
    "file per filetype. Keys registered only when an LSP server / jdtls / DAP session attaches (`gd`, `K`, `<leader>,*`,",
    "`<leader>jv*`, …) need a live server and are documented in KEYMAP_REFERENCE.md instead.",
    "",
    "| Key | Mode | Scope | Description |",
    "|-----|------|-------|-------------|",
  }
  for _, e in ipairs(rows) do
    local key = e.lhs:gsub("<Space>", "<leader>")
    table.insert(out, ("| `%s` | %s | %s | %s |"):format(esc(key), e.mode, esc(scope_label(e.scopes)), esc(e.desc)))
  end
  table.insert(out, "")
  return table.concat(out, "\n"), #rows
end

local function render_plugins()
  local cfg = require("lazy.core.config")
  local rows = {}
  for name, p in pairs(cfg.plugins) do
    local trig = {}
    if p.event then
      table.insert(trig, "event")
    end
    if p.cmd then
      table.insert(trig, "cmd")
    end
    if p.ft then
      table.insert(trig, "ft")
    end
    if p.keys then
      table.insert(trig, "keys")
    end
    if p.lazy == false then
      trig = { "startup" }
    end
    table.insert(
      rows,
      { name = name, url = (p[1] or ""), trig = #trig > 0 and table.concat(trig, "+") or "on-require" }
    )
  end
  table.sort(rows, function(a, b)
    return a.name < b.name
  end)
  local out = {
    "<!-- GENERATED by scripts/gen_docs.lua — do not edit. -->",
    "# Plugins (generated)",
    "",
    ("%d plugins. `Loads on` = lazy.nvim trigger (startup / event / cmd / ft / keys / on-require)."):format(#rows),
    "",
    "| Plugin | Repo | Loads on |",
    "|--------|------|----------|",
  }
  for _, r in ipairs(rows) do
    table.insert(out, ("| %s | `%s` | %s |"):format(esc(r.name), esc(r.url), r.trig))
  end
  table.insert(out, "")
  return table.concat(out, "\n"), #rows
end

local function read(p)
  local f = io.open(p, "r")
  if not f then
    return nil
  end
  local s = f:read("*a")
  f:close()
  return s
end

vim.defer_fn(function()
  local db = lib.collect()
  local km, nk = render_keymaps(db)
  local pl, np = render_plugins()
  vim.fn.mkdir(cfgdir .. "/docs", "p")
  local stale = {}
  for _, item in ipairs({ { "docs/KEYMAPS.generated.md", km }, { "docs/PLUGINS.generated.md", pl } }) do
    local path = cfgdir .. "/" .. item[1]
    if check then
      if read(path) ~= item[2] then
        table.insert(stale, item[1])
      end
    else
      local f = assert(io.open(path, "w"))
      f:write(item[2])
      f:close()
    end
  end
  print(
    ("gen_docs: %d keymaps, %d plugins%s"):format(
      nk,
      np,
      check and (#stale == 0 and " — docs up to date" or "") or " — written"
    )
  )
  for _, s in ipairs(stale) do
    print("  STALE: " .. s)
  end
  vim.cmd(#stale == 0 and "qa!" or "cquit 1")
end, 1500)
